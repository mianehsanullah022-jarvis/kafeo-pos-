-- ---------- Staff & roles ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  role text not null check (role in ('owner', 'cashier', 'kitchen', 'rider')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Only people with an active staff profile count as staff. Anyone who
-- somehow signs up without a profile sees and changes nothing.
create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active);
$$;

create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and active and role = 'owner');
$$;

-- ---------- Menu ----------
create table if not exists public.menu_categories (
  id text primary key,
  label text not null,
  sort int not null default 0
);

create table if not exists public.menu_items (
  id text primary key,
  category_id text not null references public.menu_categories (id) on update cascade,
  name text not null,
  note text not null default '',
  options jsonb not null,               -- [{"k":"S","p":999}, ...]  k='' means single price
  station text not null default 'kitchen' check (station in ('kitchen', 'bar')),
  counts text check (counts in ('pizza', 'steak', 'drink')),
  active boolean not null default true,
  sort int not null default 0
);

-- ---------- Settings (one row) ----------
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  data jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------- Riders ----------
create table if not exists public.riders (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null default '',
  active boolean not null default true
);

-- ---------- Customers & loyalty ----------
create table if not exists public.customers (
  phone text primary key,
  name text not null default '',
  address text not null default '',
  notes text not null default '',
  stamps int not null default 0,
  rewards_used int not null default 0,
  visits int not null default 0,
  total_spent numeric not null default 0,
  last_visit timestamptz,
  created_at timestamptz not null default now()
);

-- ---------- Orders ----------
create table if not exists public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users (id),
  type text not null check (type in ('dine', 'take', 'deliv')),
  table_no text not null default '',
  customer_phone text not null default '',
  customer_name text not null default '',
  address text not null default '',
  items jsonb not null,                 -- [{"id","name","price","qty","station","counts"}]
  notes text not null default '',
  subtotal numeric not null default 0,
  discount numeric not null default 0,
  discount_label text not null default '',
  tax numeric not null default 0,
  delivery_fee numeric not null default 0,
  total numeric not null default 0,
  payment text not null default '',     -- Cash / Card / JazzCash / Easypaisa / COD
  paid boolean not null default false,
  status text not null default 'new' check (status in ('new', 'preparing', 'ready', 'out', 'done', 'cancelled')),
  rider_id bigint references public.riders (id),
  reward text not null default ''       -- Buy More Save More freebie, if any
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = public as $$ begin new.updated_at = now(); return new; end $$;

-- The role checks are only needed by signed-in staff.
revoke execute on function public.is_staff() from anon, public;
revoke execute on function public.is_owner() from anon, public;
grant execute on function public.is_staff() to authenticated;
grant execute on function public.is_owner() to authenticated;

drop trigger if exists orders_touch on public.orders;
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

-- ---------- Security: row level security ----------
alter table public.profiles enable row level security;
alter table public.menu_categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.settings enable row level security;
alter table public.riders enable row level security;
alter table public.customers enable row level security;
alter table public.orders enable row level security;

drop policy if exists "staff read profiles" on public.profiles;
create policy "staff read profiles" on public.profiles for select using (public.is_staff());
drop policy if exists "owner manage profiles" on public.profiles;
create policy "owner manage profiles" on public.profiles for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff read categories" on public.menu_categories;
create policy "staff read categories" on public.menu_categories for select using (public.is_staff());
drop policy if exists "owner manage categories" on public.menu_categories;
create policy "owner manage categories" on public.menu_categories for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff read items" on public.menu_items;
create policy "staff read items" on public.menu_items for select using (public.is_staff());
drop policy if exists "owner manage items" on public.menu_items;
create policy "owner manage items" on public.menu_items for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff read settings" on public.settings;
create policy "staff read settings" on public.settings for select using (public.is_staff());
drop policy if exists "owner manage settings" on public.settings;
create policy "owner manage settings" on public.settings for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff read riders" on public.riders;
create policy "staff read riders" on public.riders for select using (public.is_staff());
drop policy if exists "owner manage riders" on public.riders;
create policy "owner manage riders" on public.riders for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff use customers" on public.customers;
create policy "staff use customers" on public.customers for all using (public.is_staff()) with check (public.is_staff());

drop policy if exists "staff read orders" on public.orders;
create policy "staff read orders" on public.orders for select using (public.is_staff());
drop policy if exists "staff create orders" on public.orders;
create policy "staff create orders" on public.orders for insert with check (public.is_staff());
drop policy if exists "staff update orders" on public.orders;
create policy "staff update orders" on public.orders for update using (public.is_staff()) with check (public.is_staff());
drop policy if exists "owner delete orders" on public.orders;
create policy "owner delete orders" on public.orders for delete using (public.is_owner());

