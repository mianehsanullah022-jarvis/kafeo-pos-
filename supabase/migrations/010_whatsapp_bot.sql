-- KAFEO POS update 10: WhatsApp bot (Supabase Edge Function `wa-bot`).
-- Customers chat with the KAFEO WhatsApp number. The bot answers questions, books tables,
-- and puts orders on the POS as 'pending' (same as website orders) — a cashier still
-- taps Accept before anything goes to the kitchen.
-- Safe to run more than once.

-- Chat memory: one row per customer number.
create table if not exists public.wa_contacts (
  phone text primary key,                      -- 03001234567
  wa_id text not null default '',              -- 923001234567 (as WhatsApp sends it)
  name text not null default '',
  paused_until timestamptz,                    -- staff took over the chat → bot stays quiet until then
  created_at timestamptz not null default now(),
  last_in timestamptz
);

-- Last messages of each chat, so the bot remembers what was said.
create table if not exists public.wa_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  phone text not null,
  role text not null check (role in ('user', 'assistant', 'staff')),
  body text not null default '',
  wamid text                                   -- WhatsApp message id (stops double replies)
);
create unique index if not exists wa_messages_wamid_uidx on public.wa_messages (wamid) where wamid is not null;
create index if not exists wa_messages_phone_idx on public.wa_messages (phone, created_at desc);

-- Table bookings (from WhatsApp now; the website can use it later too).
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  source text not null default 'whatsapp',
  phone text not null default '',
  name text not null default '',
  day date not null,
  time text not null default '',               -- 19:30
  people int not null default 2 check (people between 1 and 60),
  area text not null default '',               -- e.g. VIP seating, upstairs hall
  notes text not null default '',
  status text not null default 'new' check (status in ('new', 'confirmed', 'cancelled'))
);
create index if not exists bookings_day_idx on public.bookings (day, time);

-- Private settings for the bot (nobody can read this from the app).
create table if not exists public.wa_config (
  id int primary key default 1 check (id = 1),
  notify_secret text not null default encode(extensions.gen_random_bytes(24), 'hex')
);
insert into public.wa_config (id) values (1) on conflict (id) do nothing;

alter table public.wa_contacts enable row level security;
alter table public.wa_messages enable row level security;
alter table public.bookings enable row level security;
alter table public.wa_config enable row level security;   -- no policies = only the server can touch it

drop policy if exists "staff read wa contacts" on public.wa_contacts;
create policy "staff read wa contacts" on public.wa_contacts for select using (public.is_staff());
drop policy if exists "staff read wa messages" on public.wa_messages;
create policy "staff read wa messages" on public.wa_messages for select using (public.is_staff());
drop policy if exists "staff use bookings" on public.bookings;
create policy "staff use bookings" on public.bookings for all using (public.is_staff()) with check (public.is_staff());

-- When the cashier accepts / rejects a WhatsApp order, or it is ready / out for delivery,
-- the database pings the bot so it can message the customer straight away.
create extension if not exists pg_net;

create or replace function public.wa_order_status_ping() returns trigger
language plpgsql security definer set search_path = public, extensions as $$
declare s text;
begin
  if coalesce(new.meta->>'source', '') <> 'whatsapp' then return new; end if;
  if new.status is not distinct from old.status then return new; end if;
  select notify_secret into s from public.wa_config where id = 1;
  perform net.http_post(
    url := 'https://tcsigufnamlqssraignw.supabase.co/functions/v1/wa-bot',
    body := jsonb_build_object('notify', new.id, 'status', new.status),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-kafeo-notify', s)
  );
  return new;
exception when others then
  return new;                                -- never block the POS because of a message
end $$;
revoke execute on function public.wa_order_status_ping() from anon, authenticated, public;

drop trigger if exists orders_wa_status on public.orders;
create trigger orders_wa_status after update of status on public.orders
  for each row execute function public.wa_order_status_ping();
