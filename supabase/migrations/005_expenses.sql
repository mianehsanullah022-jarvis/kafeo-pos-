-- KAFEO POS update 5: expenses (petty cash, bills, purchases paid from the till).
-- Safe to run more than once.
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  amount numeric not null check (amount > 0),
  method text not null default 'Cash',
  type text not null default 'Other',
  description text not null default '',
  by_name text not null default '',
  created_by uuid references auth.users (id)
);
create index if not exists expenses_created_idx on public.expenses (created_at desc);

alter table public.expenses enable row level security;
drop policy if exists "staff read expenses" on public.expenses;
create policy "staff read expenses" on public.expenses for select using (public.is_staff());
drop policy if exists "staff add expenses" on public.expenses;
create policy "staff add expenses" on public.expenses for insert with check (public.is_staff());
drop policy if exists "owner manage expenses" on public.expenses;
create policy "owner manage expenses" on public.expenses for delete using (public.is_owner());
drop policy if exists "owner edit expenses" on public.expenses;
create policy "owner edit expenses" on public.expenses for update using (public.is_owner()) with check (public.is_owner());
