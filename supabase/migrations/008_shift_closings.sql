-- KAFEO POS update 8: shift closing (cash-up at the end of each shift).
-- Sales, card and discounts come from the orders; expenses from the expenses table.
-- The till count keeps the cash notes and every loan / company slip that is counted as cash in the till.
-- Safe to run more than once.
create table if not exists public.shift_closings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  shift_from timestamptz not null,
  shift_to timestamptz not null,
  shift_name text not null default '',
  cash_sales numeric not null default 0,
  card_sales numeric not null default 0,
  discount numeric not null default 0,
  total_sale numeric not null default 0,
  received numeric not null default 0,
  received_from text not null default '',
  opening numeric not null default 0,
  total_cash numeric not null default 0,
  expenses numeric not null default 0,
  remaining numeric not null default 0,
  notes_cash numeric not null default 0,
  notes jsonb not null default '{}'::jsonb,
  slips jsonb not null default '[]'::jsonb,
  till_cash numeric not null default 0,
  difference numeric not null default 0,
  remarks text not null default '',
  orders_count int not null default 0,
  by_name text not null default '',
  created_by uuid references auth.users (id)
);
create index if not exists shift_closings_to_idx on public.shift_closings (shift_to desc);

alter table public.shift_closings enable row level security;
drop policy if exists "staff read closings" on public.shift_closings;
create policy "staff read closings" on public.shift_closings for select using (public.is_staff());
drop policy if exists "staff add closings" on public.shift_closings;
create policy "staff add closings" on public.shift_closings for insert with check (public.is_staff());
drop policy if exists "owner edit closings" on public.shift_closings;
create policy "owner edit closings" on public.shift_closings for update using (public.is_owner()) with check (public.is_owner());
drop policy if exists "owner delete closings" on public.shift_closings;
create policy "owner delete closings" on public.shift_closings for delete using (public.is_owner());

do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'shift_closings') then
    alter publication supabase_realtime add table public.shift_closings;
  end if;
end $$;
