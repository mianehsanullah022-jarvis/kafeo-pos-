-- KAFEO POS · Table Talk (QR at the table)
-- Customers scan the QR at their table. Orders arrive through the `web-order`
-- Edge Function as 'pending' dine-in orders with the table number.
-- Waiter calls ("bring water", "bring the bill"...) land in this table and pop up on the POS
-- until a staff member taps Done. Only the Edge Function (service role) can add calls.
-- Safe to run more than once.
create table if not exists public.table_calls (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  table_no text not null,
  request text not null,
  status text not null default 'open' check (status in ('open', 'done')),
  done_by text not null default '',
  done_at timestamptz,
  ip text not null default ''
);
create index if not exists table_calls_open_idx on public.table_calls (status, created_at desc);

alter table public.table_calls enable row level security;
drop policy if exists "staff read table calls" on public.table_calls;
create policy "staff read table calls" on public.table_calls for select using (public.is_staff());
drop policy if exists "staff finish table calls" on public.table_calls;
create policy "staff finish table calls" on public.table_calls for update using (public.is_staff()) with check (public.is_staff());

do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'table_calls') then
    alter publication supabase_realtime add table public.table_calls;
  end if;
end $$;
