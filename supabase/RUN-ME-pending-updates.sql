-- ===== 003_menu_photos =====
-- KAFEO POS update 3: item photos on the order screen.
-- Adds a photo link to each menu item and a public "menu" photo store that only the owner can upload to.
-- Safe to run more than once.
alter table public.menu_items add column if not exists image_url text not null default '';

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('menu', 'menu', true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "owner uploads menu photos" on storage.objects;
create policy "owner uploads menu photos" on storage.objects for insert to authenticated
  with check (bucket_id = 'menu' and public.is_owner());
drop policy if exists "owner updates menu photos" on storage.objects;
create policy "owner updates menu photos" on storage.objects for update to authenticated
  using (bucket_id = 'menu' and public.is_owner()) with check (bucket_id = 'menu' and public.is_owner());
drop policy if exists "owner deletes menu photos" on storage.objects;
create policy "owner deletes menu photos" on storage.objects for delete to authenticated
  using (bucket_id = 'menu' and public.is_owner());

-- ===== 004_inventory =====
-- KAFEO POS update 4: inventory — stock items, recipes, stock movements.
-- Stock levels change only through stock_moves (a trigger keeps stock_items.qty in step),
-- so purchases, sales, waste and counts from every device add up correctly.
-- Safe to run more than once.

create table if not exists public.stock_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'General',
  unit text not null default 'pcs',          -- kg, g, L, ml, pcs, pack, dozen
  qty numeric not null default 0,
  low_level numeric not null default 0,       -- warn when qty is at or below this
  cost numeric not null default 0,            -- cost price per unit
  supplier text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  menu_item_id text not null references public.menu_items (id) on delete cascade,
  option_key text not null default '',        -- size: '', 'S', 'M', 'L', '500ml' …
  stock_item_id bigint not null references public.stock_items (id) on delete cascade,
  qty numeric not null check (qty > 0),
  unique (menu_item_id, option_key, stock_item_id)
);

create table if not exists public.stock_moves (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  stock_item_id bigint not null references public.stock_items (id) on delete cascade,
  change numeric not null,                    -- + in, − out
  kind text not null check (kind in ('purchase', 'sale', 'return', 'waste', 'adjust', 'opening')),
  note text not null default '',
  order_id bigint,
  unit_cost numeric not null default 0,
  by_name text not null default ''
);
create index if not exists stock_moves_created_idx on public.stock_moves (created_at desc);
create index if not exists stock_moves_item_idx on public.stock_moves (stock_item_id);

-- Every movement updates the stock level (and, for purchases, the latest cost price).
create or replace function public.apply_stock_move() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.stock_items
     set qty = qty + new.change,
         cost = case when new.kind = 'purchase' and new.unit_cost > 0 then new.unit_cost else cost end
   where id = new.stock_item_id;
  return new;
end $$;
drop trigger if exists stock_moves_apply on public.stock_moves;
create trigger stock_moves_apply after insert on public.stock_moves
  for each row execute function public.apply_stock_move();
revoke execute on function public.apply_stock_move() from anon, public;

alter table public.stock_items enable row level security;
alter table public.recipes enable row level security;
alter table public.stock_moves enable row level security;

drop policy if exists "staff read stock" on public.stock_items;
create policy "staff read stock" on public.stock_items for select using (public.is_staff());
drop policy if exists "owner manage stock" on public.stock_items;
create policy "owner manage stock" on public.stock_items for all using (public.is_owner()) with check (public.is_owner());

drop policy if exists "staff read recipes" on public.recipes;
create policy "staff read recipes" on public.recipes for select using (public.is_staff());
drop policy if exists "owner manage recipes" on public.recipes;
create policy "owner manage recipes" on public.recipes for all using (public.is_owner()) with check (public.is_owner());

-- Any staff member can record movements (sales from the counter, purchases, waste); only the owner can delete.
drop policy if exists "staff read moves" on public.stock_moves;
create policy "staff read moves" on public.stock_moves for select using (public.is_staff());
drop policy if exists "staff add moves" on public.stock_moves;
create policy "staff add moves" on public.stock_moves for insert with check (public.is_staff());
drop policy if exists "owner delete moves" on public.stock_moves;
create policy "owner delete moves" on public.stock_moves for delete using (public.is_owner());

do $$
begin
  begin alter publication supabase_realtime add table public.stock_items; exception when duplicate_object then null; end;
end $$;

-- ===== 005_expenses =====
-- KAFEO POS update 5: expenses (petty cash, bills, purchases paid from the till).
-- Safe to run more than once.
create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  amount numeric not null check (amount > 0),
  method text not null default 'Cash',
  type text not null default 'Other',
  description text not null default '',
  by_name text not null default '',
  created_by uuid references auth.users (id)
);
create index if not exists expenses_created_idx on public.expenses (created_at desc);

alter table public.expenses enable row level security;
drop policy if exists "staff read expenses" on public.expenses;
create policy "staff read expenses" on public.expenses for select using (public.is_staff());
drop policy if exists "staff add expenses" on public.expenses;
create policy "staff add expenses" on public.expenses for insert with check (public.is_staff());
drop policy if exists "owner manage expenses" on public.expenses;
create policy "owner manage expenses" on public.expenses for delete using (public.is_owner());
drop policy if exists "owner edit expenses" on public.expenses;
create policy "owner edit expenses" on public.expenses for update using (public.is_owner()) with check (public.is_owner());
